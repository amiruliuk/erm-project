-- ERM-MBPLC v4: Units inside departments (PostgreSQL)
-- application.properties uses spring.jpa.hibernate.ddl-auto=validate, so run this script ONCE
-- against the database BEFORE starting the new version (otherwise start-up fails schema validation).
-- Take a backup first.

BEGIN;

CREATE TABLE IF NOT EXISTS units (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     TIMESTAMP(6) NOT NULL,
    updated_at     TIMESTAMP(6),
    name           VARCHAR(255) NOT NULL,
    code           VARCHAR(255),
    description    VARCHAR(1000),
    active         BOOLEAN NOT NULL DEFAULT TRUE,
    department_id  BIGINT NOT NULL REFERENCES departments(id),
    unit_head_id   BIGINT REFERENCES employees(id),
    CONSTRAINT uk_units_code      UNIQUE (code),
    CONSTRAINT uk_units_dept_name UNIQUE (department_id, name)
);

ALTER TABLE employees ADD COLUMN IF NOT EXISTS unit_id        BIGINT REFERENCES units(id);
ALTER TABLE projects  ADD COLUMN IF NOT EXISTS owning_unit_id BIGINT REFERENCES units(id);

CREATE INDEX IF NOT EXISTS idx_units_department   ON units(department_id);
CREATE INDEX IF NOT EXISTS idx_employees_unit     ON employees(unit_id);
CREATE INDEX IF NOT EXISTS idx_projects_own_unit  ON projects(owning_unit_id);

COMMIT;
